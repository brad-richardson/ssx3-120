#!/usr/bin/env python3
"""Regenerate tools/ssx3/tricky/shared/refpack_cand_order.h.

The optimal-parse DP in refpack_optimal.py iterates long-match length
candidates via a Python ``set``::

    lengths = {length, length - 1, length - 2, length - 3, 10, 67, 16} \\
        - set(range(0, minimum))

Within-set cost ties are common (not rare), so the native port must visit
those lengths in exactly the set's iteration order to stay byte-identical.
That order is a pure function of ``length`` (int hashing is value-based,
hence hash-seed independent; ``minimum`` never removes a member since all
values are >= 10 > minimum) and is identical on macOS/arm64 Python 3.15 and
Linux/x86_64 Python 3.12 (verified [native-refpack-1]). This script dumps the
observed order for every length 17..1028 as a C header the native encoder
includes. Re-run to verify: the output must be byte-identical.
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / 'refpack_cand_order.h'


def main():
    rows = {}
    for length in range(17, 1029):
        seen = set()
        for minimum in (3, 4, 5):
            seen.add(tuple({length, length - 1, length - 2, length - 3,
                            10, 67, 16} - set(range(0, minimum))))
        assert len(seen) == 1, length
        rows[length] = seen.pop()
    lines = [
        '/* Generated by gen_cand_order.py - do not edit by hand. */',
        '/* Iteration order of {length,length-1,length-2,length-3,10,67,16} */',
        '/* as a Python set, for length = 17..1028. */',
        'static const short RP_CAND_ORDER[1029][7] = {',
    ]
    counts = []
    for length in range(1029):
        if length in rows:
            vals = rows[length]
            counts.append(len(vals))
            pad = [0] * (7 - len(vals))
            lines.append('    {%s}, /* %d */' %
                         (', '.join(str(v) for v in list(vals) + pad), length))
        else:
            counts.append(0)
            lines.append('    {0, 0, 0, 0, 0, 0, 0},')
    lines.append('};')
    lines.append('static const unsigned char RP_CAND_COUNT[1029] = {')
    lines.append('    %s' % ', '.join(
        str(len(rows[l]) if l in rows else 0) for l in range(1029)))
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'wrote {OUT} ({sum(counts)} values)')


if __name__ == '__main__':
    sys.exit(main())
