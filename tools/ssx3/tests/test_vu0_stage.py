build = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(build)

ROOT = Path(__file__).resolve().parents[3]

VALID_IMAGE = (
    '// Generated by PS2X_VU0_RECOMP_DUMP (VR3). Derived from game data:\n'
    '#include "ps2_vu0_recomp_gen.h"\n'
    'using VU0 = VU0Interpreter;\n'
    'template <>\n'
    'struct VU0RecompImage<0x40829a098c260b4full>\n'
    '{ /* kPairs kBlockPairs kGroupPairs tables elided */ };\n'
    'const VU0::RecompPairFn VU0RecompImage<0x1>::kGroupPairs[512] = {};\n'
)


def make_stage(parent, name='vu0e_40829a098c260b4f.cpp', text=VALID_IMAGE):
    stage = Path(parent) / 'stage'
    stage.mkdir(parents=True, exist_ok=True)
    (stage / name).write_text(text)
    return stage


def make_work_with_stage(tmp):
    work = Path(tmp) / 'work'
    work.mkdir(parents=True)
    (work / 'SLUS_207.72').write_bytes(b'elf-bytes')
    stage = make_stage(work / 'src')
    target = work / 'vu0-stage'
    target.mkdir()
    (target / 'vu0e_40829a098c260b4f.cpp').write_text(VALID_IMAGE)
    receipt = {'elf_sha256': build.sha(work / 'SLUS_207.72'),
               'engine': 'abc123',
               'outputs_sha256': build.vu0_stage_file_hashes(target)}
    (work / 'vu0-stage.json').write_text(json.dumps(receipt))
    return work, stage


