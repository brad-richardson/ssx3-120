class AndroidWiringTest(unittest.TestCase):
    def run_android(self, work, extra):
        seen = {}

        def fake_run(*args, **kwargs):
            seen['args'] = list(map(str, args))

        jni = work / 'jniLibs'
        (jni / 'arm64-v8a').mkdir(parents=True)
        base = dict(work=work, jnilibs=jni, prebuilt=False, no_turnip=True,
                    app_id=build.PUBLIC_APP_ID, jobs=2)
        base.update(extra)
        a = types.SimpleNamespace(**base)
        with patch.object(build, 'ensure_android_toolchain'), \
             patch.object(build, 'support_bundle', return_value=None), \
             patch.object(build, 'ensure_keystore', return_value=work / 'k'), \
             patch.object(build, 'next_version_code', return_value=1), \
             patch.object(build, 'run', side_effect=fake_run):
            with redirect_stdout(io.StringIO()):
                build.android(a)
        vu0_args = [x for x in seen['args'] if x.startswith('-Pps2xVu0RecompDir=')]
        self.assertEqual(len(vu0_args), 1)
        return vu0_args[0]

    def test_android_passes_explicit_stage_to_gradle(self):
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / 'work'
            work.mkdir()
            stage = make_stage(tmp)
            got = self.run_android(work, {'vu0_stage': stage})
            self.assertEqual(got, '-Pps2xVu0RecompDir=' + str(stage))

    def test_android_passes_empty_without_stage(self):
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / 'work'
            work.mkdir()
            got = self.run_android(work, {})
            self.assertEqual(got, '-Pps2xVu0RecompDir=')


class MacWiringTest(unittest.TestCase):
    def test_mac_passes_resolved_dir_to_cmake(self):
        seen = {}

        def fake_configure(src, dst, *flags):
            seen['flags'] = list(map(str, flags))

        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / 'work'
            work.mkdir()
            stage = make_stage(tmp)
            a = types.SimpleNamespace(work=work, suite=False, det=False, jobs=2,
                                      vu0_stage=stage)
            with patch.object(build, 'configure', side_effect=fake_configure), \
                 patch.object(build, 'run'):
                with redirect_stdout(io.StringIO()):
                    build.mac(a)
        vu0_flags = [x for x in seen['flags'] if x.startswith('-DPS2X_VU0_RECOMP_DIR=')]
        self.assertEqual(vu0_flags, ['-DPS2X_VU0_RECOMP_DIR=' + str(stage)])


