"""VU0 image staging (build-parity-fix-1 D03) plus the D01/D02 pins.

No network, no disc, no NDK, no device: stages are synthetic, heavy build
steps are stubbed, and file-content pins are read from the checkout.
"""
import importlib.util
import io
import json
import tempfile
import types
import unittest
from contextlib import redirect_stdout
from pathlib import Path
from unittest.mock import patch

BUILD = Path(__file__).resolve().parents[1] / 'build.py'
SPEC = importlib.util.spec_from_file_location('ssx3_build_vu0', BUILD)
build = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(build)

ROOT = Path(__file__).resolve().parents[3]

VALID_IMAGE = (
    '// Generated by PS2X_VU0_RECOMP_DUMP (VR3). Derived from game data:\n'
    '#include "ps2_vu0_recomp_gen.h"\n'
    'using VU0 = VU0Interpreter;\n'
    'template <>\n'
    'struct VU0RecompImage<0x40829a098c260b4full>\n'
    '{ /* kPairs kBlockPairs kGroupPairs tables elided */ };\n'
    'const VU0::RecompPairFn VU0RecompImage<0x1>::kGroupPairs[512] = {};\n'
)


def make_stage(parent, name='vu0e_40829a098c260b4f.cpp', text=VALID_IMAGE):
    stage = Path(parent) / 'stage'
    stage.mkdir(parents=True, exist_ok=True)
    (stage / name).write_text(text)
    return stage


def make_work_with_stage(tmp):
    work = Path(tmp) / 'work'
    work.mkdir(parents=True)
    (work / 'SLUS_207.72').write_bytes(b'elf-bytes')
    stage = make_stage(work / 'src')
    target = work / 'vu0-stage'
    target.mkdir()
    (target / 'vu0e_40829a098c260b4f.cpp').write_text(VALID_IMAGE)
    receipt = {'elf_sha256': build.sha(work / 'SLUS_207.72'),
               'engine': 'abc123',
               'outputs_sha256': build.vu0_stage_file_hashes(target)}
    (work / 'vu0-stage.json').write_text(json.dumps(receipt))
    return work, stage


class ValidateTest(unittest.TestCase):
    def test_valid_stage(self):
        with tempfile.TemporaryDirectory() as tmp:
            stage = make_stage(tmp)
            self.assertEqual(build.validate_vu0_stage(stage), stage)

    def test_missing_dir(self):
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaises(ValueError):
                build.validate_vu0_stage(Path(tmp) / 'nope')

    def test_empty_dir(self):
        with tempfile.TemporaryDirectory() as tmp:
            empty = Path(tmp) / 'empty'
            empty.mkdir()
            with self.assertRaises(ValueError):
                build.validate_vu0_stage(empty)

    def test_non_image_content_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            stage = make_stage(tmp, text='// not a VU0 image\n')
            with self.assertRaises(ValueError):
                build.validate_vu0_stage(stage)


class HashesTest(unittest.TestCase):
    def test_hashes_map_names(self):
        with tempfile.TemporaryDirectory() as tmp:
            stage = make_stage(tmp)
            hashes = build.vu0_stage_file_hashes(stage)
            self.assertEqual(list(hashes), ['vu0e_40829a098c260b4f.cpp'])
            self.assertRegex(hashes['vu0e_40829a098c260b4f.cpp'], r'^[0-9a-f]{64}$')

    def test_none_when_empty(self):
        with tempfile.TemporaryDirectory() as tmp:
            empty = Path(tmp) / 'empty'
            empty.mkdir()
            self.assertIsNone(build.vu0_stage_file_hashes(empty))


class CurrentTest(unittest.TestCase):
    def test_false_without_receipt(self):
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / 'work'
            work.mkdir()
            (work / 'SLUS_207.72').write_bytes(b'elf-bytes')
            self.assertFalse(build.vu0_current(work))

    def test_true_after_publish(self):
        with tempfile.TemporaryDirectory() as tmp:
            work, _ = make_work_with_stage(tmp)
            self.assertTrue(build.vu0_current(work))

    def test_false_on_output_tamper(self):
        with tempfile.TemporaryDirectory() as tmp:
            work, _ = make_work_with_stage(tmp)
            (work / 'vu0-stage/vu0e_40829a098c260b4f.cpp').write_text(VALID_IMAGE + '// x\n')
            self.assertFalse(build.vu0_current(work))

    def test_false_on_elf_change(self):
        with tempfile.TemporaryDirectory() as tmp:
            work, _ = make_work_with_stage(tmp)
            (work / 'SLUS_207.72').write_bytes(b'other-elf')
            self.assertFalse(build.vu0_current(work))


class PublishTest(unittest.TestCase):
    def test_publish_swaps_stage_atomically(self):
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / 'work'
            work.mkdir()
            (work / 'SLUS_207.72').write_bytes(b'elf-bytes')
            new = work / 'vu0-stage.new'
            new.mkdir()
            (new / 'vu0e_40829a098c260b4f.cpp').write_text(VALID_IMAGE)
            hashes = build.vu0_stage_file_hashes(new)
            stage = build.publish_vu0_stage(work, new, {'elf_sha256': 'e', 'outputs_sha256': hashes})
            self.assertEqual(stage, work / 'vu0-stage')
            self.assertFalse(new.exists())
            receipt = json.loads((work / 'vu0-stage.json').read_text())
            self.assertEqual(receipt['outputs_sha256'], hashes)


