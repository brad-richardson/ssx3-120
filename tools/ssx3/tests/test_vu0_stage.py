class ResolveTest(unittest.TestCase):
    def test_explicit_stage_wins(self):
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / 'work'
            work.mkdir()
            stage = make_stage(tmp)
            a = types.SimpleNamespace(work=work, vu0_stage=stage)
            self.assertEqual(build.resolve_vu0_stage(a), str(stage))

    def test_explicit_invalid_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / 'work'
            work.mkdir()
            a = types.SimpleNamespace(work=work, vu0_stage=Path(tmp) / 'nope')
            with self.assertRaises(ValueError):
                build.resolve_vu0_stage(a)

    def test_missing_default_resolves_empty(self):
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / 'work'
            work.mkdir()
            a = types.SimpleNamespace(work=work)
            out = io.StringIO()
            with redirect_stdout(out):
                self.assertEqual(build.resolve_vu0_stage(a), '')
            self.assertIn('interpreter-only', out.getvalue())

    def test_current_default_resolves_path(self):
        with tempfile.TemporaryDirectory() as tmp:
            work, _ = make_work_with_stage(tmp)
            a = types.SimpleNamespace(work=work)
            out = io.StringIO()
            with redirect_stdout(out):
                self.assertEqual(build.resolve_vu0_stage(a), str(work / 'vu0-stage'))
            self.assertIn('current', out.getvalue())


